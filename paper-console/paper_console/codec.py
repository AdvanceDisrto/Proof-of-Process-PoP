"""Strict receipt-derived event contract; visualization NEVER upgrades proof tiers."""
from __future__ import annotations
from dataclasses import dataclass, asdict
import hashlib
import json
import re
import time

CLAIMS = frozenset({"PROVEN_TRUE", "REFUTED_FALSE", "UNRESOLVED", "NOT_APPLICABLE"})
DECISIONS = frozenset({"VERIFIED_DIGITAL_RECEIPT", "CRYPTOGRAPHIC_ATTESTATION_ONLY", "REJECTED", "NOT_CHECKED"})
TRACKS = frozenset({"claim", "atlas", "subsea", "covariance", "energy", "popc", "transit"})
MAX_DATA_BYTES = 8000


def canonical(obj: object) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
                      allow_nan=False).encode("utf-8")


def sha256(obj: object) -> str:
    return hashlib.sha256(canonical(obj)).hexdigest()


class InvalidEvent(ValueError):
    pass


@dataclass(frozen=True)
class Event:
    event_id: str
    occurred_at: int
    track: str
    subject: str
    claim_verdict: str
    verification: str
    details: dict
    source_tier: str
    source_ref: str | None = None
    receipt_sha256: str | None = None
    carrier: str | None = None
    observed_joules: float | None = None

    def __post_init__(self):
        if not re.fullmatch(r"[A-Za-z0-9_:\-]{5,100}", self.event_id):
            raise InvalidEvent("event_id requires 5-100 safe characters")
        if type(self.occurred_at) is not int or self.occurred_at < 0:
            raise InvalidEvent("invalid integer event timestamp")
        if self.track not in TRACKS or self.claim_verdict not in CLAIMS:
            raise InvalidEvent("unknown track or claim verdict")
        if self.verification not in DECISIONS:
            raise InvalidEvent("unknown verification decision")
        if type(self.subject) is not str or not 1 <= len(self.subject) <= 200 or any(ord(c) < 32 for c in self.subject):
            raise InvalidEvent("invalid subject")
        if type(self.details) is not dict or len(canonical(self.details)) > MAX_DATA_BYTES:
            raise InvalidEvent("details must be bounded JSON")
        if self.source_tier not in {"DEMO", "OPERATOR_UNVERIFIED", "DATASET_UNVERIFIED", "SIGNED_DIGITAL", "INA226_CALIBRATED_UNATTESTED", "MATH_COMPUTED"}:
            raise InvalidEvent("unknown source tier")
        if self.source_ref is not None and (type(self.source_ref) is not str or len(self.source_ref) > 300):
            raise InvalidEvent("invalid source reference")
        if self.receipt_sha256 is not None and not re.fullmatch(r"[0-9a-f]{64}", self.receipt_sha256):
            raise InvalidEvent("invalid receipt SHA-256")
        if self.carrier is not None and (type(self.carrier) is not str or len(self.carrier) > 12000 or not self.carrier.startswith("ipqr1:")):
            raise InvalidEvent("carrier must be a bounded signed ipqr1 text")
        if self.observed_joules is not None:
            if type(self.observed_joules) not in (int, float) or not 0 <= self.observed_joules < 1e9:
                raise InvalidEvent("invalid claimed joules")
        if self.verification == "VERIFIED_DIGITAL_RECEIPT":
            if self.source_tier != "SIGNED_DIGITAL" or self.receipt_sha256 is None:
                raise InvalidEvent("verified receipt requires verified signature evidence")

    def as_dict(self) -> dict:
        return asdict(self)


def event_from_verifier(packet: dict, decision: dict, *, carrier: str | None = None,
                        when: int | None = None) -> Event:
    """Re-export a verdict ONLY from results generated by the independent verifier.

    The caller must actually invoke independent verifier first (see verification.py);
    accepting arbitrary decision dicts here alone is not an authentication boundary.
    """
    r = packet["receipt"]
    claim_code = r["verdict"]
    return Event(event_id=f"ipqr-{decision['receipt_sha256'][:32]}",
                 occurred_at=int(time.time()) if when is None else when,
                 track="claim", subject=r["subject"], claim_verdict=claim_code,
                 verification=decision["code"],
                 details={"claim_sha256": r["claim_sha256"],
                          "proof_scope": decision.get("proof_scope"),
                          "accountable_human": (decision.get("accountable_human") or {}).get("id")},
                 source_tier="SIGNED_DIGITAL" if decision["verified"] else "OPERATOR_UNVERIFIED",
                 receipt_sha256=decision["receipt_sha256"], carrier=carrier,
                 observed_joules=(r.get("energy_microjoules") / 1e6 if r.get("energy_microjoules") is not None else None))
